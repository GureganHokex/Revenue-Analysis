#Функция для создания файла
def files_create(month_name, shifts_objects, rate_per_shifts_list, incomes, expenses):
    """
    Создает и сохраняет простой файл-отчет за указанный месяц: запрашивает у пользователя
    формат файла и имя, затем записывает переданные данные о сменах и финансах в файл.

    Поведение
    - Запрашивает у пользователя через input():
        - format_file: расширение файла с точкой (например ".txt", ".log")
        - name_file: базовое имя файла (обрезаются пробелы слева/справа)
    - Формирует имя файла как: "{name_file}-{month_name}{format_file}"
    - Записывает текстовый отчет в текущую рабочую директорию в кодировке UTF-8.
    - В отчете присутствуют разделы: "Смены", "Ставки", "Суммы (доходы)", "Расходы (общий список)"
      (каждая запись расходов — на новой строке), и подробный блок по каждой смене 
        (str(shift) на строку).
    - Печатает в stdout сообщения о попытке сохранения, текущей директории, успехе или ошибках.
    - Перехватывает PermissionError и печатает понятное сообщение; 
        другие исключения печатаются тоже.
      Функция сама исключения не пробрасывает дальше.

    Параметры
    - month_name (str):
        Человекочитаемый идентификатор месяца (используется в имени файла).
    - shifts_objects (Iterable[object]):
        Итерабель по объектам смен. Ожидается, что каждый элемент:
            - имеет атрибут/свойство `shifts_val` (для строки "Смены"), и
            - корректно преобразуется в строку через str() (для подробного блока).
    - rate_per_shifts_list (Iterable[int|float|str]):
        Итерабель ставок за смену — записывается одной строкой через запятые.
    - incomes (Iterable[int|float|str]):
        Итерабель сумм доходов — записывается одной строкой через запятые.
    - expenses (Iterable[Any]):
      Итерабель записей расходов; каждый элемент приводится к
        str() и записывается на отдельной строке.

    Примечания и предусловия
    - Файл создается в текущей рабочей директории (os.getcwd() выводится для информации). Директория
      должна быть доступна для записи.
    - Используется кодировка UTF-8.
    - Функция не проверяет корректность переданного расширения — оно должно содержать точку.
    - Значений не возвращается; функция выполняет ввод/вывод и печатает статусы.

    Побочные эффекты
    - Запрашивает ввод через input().
    - Создает/перезаписывает файл "{name_file}-{month_name}{format_file}".
    - Печатает сообщения о ходе выполнения и ошибках.

    Пример
    - Если month_name == "Январь", ввод name_file == "отчет", format_file == ".txt",
      будет создан файл "отчет-Январь.txt" в текущей рабочей директории.
    """
    format_file = input("Введите желаемый формат файла:(через точку, например .txt,.log): ")
    name_file = input("Какое будет название файла: ").strip()
    files = f'{name_file}-{month_name}{format_file}'
    print(f"Попытка сохранить файл: {files}")
    print(f"Текущая рабочая директория: {os.getcwd()}")
    try:
        with open(files, 'w', encoding='utf-8') as file:
            # Записываем отдельно списки
            file.write('Смены:\n')
            # записи по сменам (значения)
            file.write(', '.join(str(shift.shifts_val) for shift in shifts_objects) + '\n\n')

            file.write('Ставки:\n')
            file.write(', '.join(str(r) for r in rate_per_shifts_list) + '\n\n')

            file.write('Суммы (доходы):\n')
            file.write(', '.join(str(i) for i in incomes) + '\n\n')

            file.write('Расходы (общий список):\n')
            for exp in expenses:
                file.write(f'{exp}\n')

            # опционально — подробная информация по каждой смене
            file.write('\nПодробно по сменам:\n')
            for shift in shifts_objects:
                file.write(str(shift) + '\n')
        print(f"Данные успешно сохранены в файл: {files}")
    except PermissionError:
        print("Ошибка: Отказано в доступе. Попробуйте сохранить файл в другую папку.")
    except (OSError, TypeError, AttributeError) as e:
        print(f"Произошла непредвиденная ошибка при сохранении файла: {e}")
#Функция для добавления расходов в список
def expenses_create(expenses_list,for_what,how_much):
    """
    Добавляет запись о расходе в список и возвращает его.

    Параметры
    ----------
    expenses_list : list
        Список расходов (мутируется). Каждая запись — строка.
    for_what : str
        Описание или категория расхода.
    how_much : int | float | str
        Сумма расхода (будет приведена к строке).

    Возвращает
    -------
    list
        Тот же объект expenses_list с добавленной записью в формате "<for_what> - <how_much>".

    Примечание
    ------
    Если не хотите изменять исходный список, передайте его копию (например, expenses_list.copy()).
    """
    expenses_list.append(f'{for_what} - {how_much}')
    return expenses_list
